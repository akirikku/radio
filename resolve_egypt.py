#!/usr/bin/env python3
"""Resolve stations-egypt.md into egypt/stations.js for the Egyptian player.

Each block in stations-egypt.md is: the station name, its name in Arabic, a short tagline,
and its Zeno.FM stream link (https://stream.zeno.fm/<mount>). The player plays that link
and gets "Artist - Title" from Zeno's now-playing feed for the same mount. This checks
that each stream answers and records what the player needs.

Stations here should carry no commercials. Zeno sells pre-roll ads in its own web player;
in testing (2026-11), the direct stream links started straight into the live audio.

Run again whenever stations-egypt.md changes:  python3 resolve_egypt.py
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "stations-egypt.md"
OUT = HERE / "egypt" / "stations.js"
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"


def parse(text):
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = [l.strip() for l in block.splitlines() if l.strip()]
        url = next((l for l in lines if l.startswith("http")), None)
        rest = [l for l in lines if not l.startswith("http")]
        if url and rest:
            yield {"name": rest[0], "nameNative": rest[1] if len(rest) > 1 else None,
                   "tagline": rest[2] if len(rest) > 2 else None, "page": url}


def resolve(s):
    m = re.fullmatch(r"https://stream\.zeno\.fm/([a-z0-9]+)/?", s["page"])
    if not m:
        raise ValueError("expected a https://stream.zeno.fm/<mount> link")
    mount = m.group(1)
    # The stream servers turn away a bare "Mozilla/5.0" user agent; a full browser one passes.
    req = urllib.request.Request(s["page"], headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=15) as r:
        if not r.headers.get("content-type", "").startswith("audio/"):
            raise ValueError(f"not an audio stream ({r.headers.get('content-type')})")
    return {**s, "stream": s["page"], "source": "zeno", "mount": mount, "artFallback": "artist"}


def main():
    resolved = []
    for s in parse(SRC.read_text(encoding="utf-8")):
        try:
            resolved.append(resolve(s))
            print(f"ok   {s['name']}: {s['page']}")
        except Exception as e:  # keep going; one dead stream shouldn't break the radio
            print(f"FAIL {s['name']}: {e}", file=sys.stderr)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by resolve_egypt.py from stations-egypt.md. Do not edit by hand.\n"
        "window.STATIONS = " + json.dumps(resolved, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(resolved)} stations to {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
