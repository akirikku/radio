#!/usr/bin/env python3
"""Resolve stations.md into stations.js for the radio player.

stations.md holds blocks of "Station name" followed by its player page URL.
Each asia DREAM radio player page embeds the real Shoutcast stream URL (in
`new RTPlayer(...)`) and a now-playing widget (`api-base` + `server-id`).
We scrape those out so the browser can play the stream directly and poll
`<api-base>/history/?limit=1&server=<id>` for artist, title and artwork.

Run again whenever stations.md changes:  python3 resolve_stations.py
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "stations.md"
OUT = HERE / "stations.js"


def parse_md(text):
    stations = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = [l.strip() for l in block.splitlines() if l.strip()]
        url = next((l for l in lines if l.startswith("http")), None)
        name = next((l for l in lines if not l.startswith("http")), None)
        if url and name:
            stations.append({"name": name, "page": url})
    return stations


def resolve(station):
    req = urllib.request.Request(station["page"], headers={"User-Agent": "Mozilla/5.0"})
    html = urllib.request.urlopen(req, timeout=15).read().decode("utf-8", "replace")

    m = re.search(r'new RTPlayer\([^)]*?\{"mp3":\s*"([^"]+)"', html)
    if not m:
        raise ValueError("no stream URL found")
    # Drop the page's frozen nocache value; the player adds a fresh one.
    stream = re.sub(r"&?nocache=\d+", "", m.group(1))

    api = re.search(r'api-base="([^"]+)"', html)
    sid = re.search(r'server-id="(\d+)"', html)
    title = re.search(r"<title>(.*?)</title>", html)
    return {
        **station,
        "stream": stream,
        "api": api.group(1).rstrip("/") if api else None,
        "serverId": int(sid.group(1)) if sid else None,
        "pageTitle": title.group(1).strip() if title else None,
    }


def main():
    stations = parse_md(SRC.read_text(encoding="utf-8"))
    resolved = []
    for s in stations:
        try:
            r = resolve(s)
            resolved.append(r)
            print(f"ok   {r['name']}: {r['stream']}  (meta server {r['serverId']})")
        except Exception as e:  # keep going; one dead page shouldn't break the radio
            print(f"FAIL {s['name']}: {e}", file=sys.stderr)
    OUT.write_text(
        "// Generated by resolve_stations.py from stations.md. Do not edit by hand.\n"
        "window.STATIONS = " + json.dumps(resolved, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(resolved)} stations to {OUT.name}")


if __name__ == "__main__":
    main()
