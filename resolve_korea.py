#!/usr/bin/env python3
"""Resolve stations-korea.md into korea/stations.js for the Korean player.

stations-korea.md holds blocks of "Station name" followed by the station's page. This
radio mixes three kinds of station, each recognized by its page URL. All are free of
commercials, which is why ad-funded networks such as laut.fm are left out:

  bigbradio.net/<channel>   Big B Radio, a nonprofit on Centova Cast. The page names the
                            Centova host; the stream and "now playing" call follow from it.
  listen.moe/kpop           LISTEN.moe, listener-funded. Its stream sends no CORS header, so
                            it plays outside Web Audio (cors: false); songs arrive over a
                            WebSocket.
  onair.kbs.co.kr/...ch_code=<n>
                            KBS. Its stream links are signed and expire, so the player
                            asks KBS for a fresh one each time; here we only keep the code.

Run again whenever stations-korea.md changes:  python3 resolve_korea.py
"""
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from resolve_stations import parse_md

HERE = Path(__file__).resolve().parent
SRC = HERE / "stations-korea.md"
OUT = HERE / "korea" / "stations.js"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=15).read().decode("utf-8", "replace")


def bigb(s, url):
    channel = url.path.strip("/").split("/")[-1]
    m = re.search(r"https://([a-z0-9.-]+\.dribbcast\.com)(?::\d+)?/system/streaminfo\.js", get(url.geturl()))
    if not m:
        raise ValueError("no Centova host on the page")
    host = m.group(1)
    rpc = f"https://{host}/rpc/{channel}/streaminfo.get"
    info = json.loads(get(rpc))["data"][0]
    return {
        "stream": f"https://{host}/proxy/{channel}?mp=/s",
        "source": "centova", "rpc": rpc, "tagline": info.get("title"),
    }


def listenmoe(s, url):
    channel = url.path.strip("/") or "jpop"  # listen.moe/ is J-pop, listen.moe/kpop is K-pop
    base = "https://listen.moe" + ("/kpop" if channel == "kpop" else "")
    return {
        "stream": f"{base}/fallback",  # MP3, which every browser plays (/stream is Ogg)
        "cors": False,
        "source": "listenmoe", "gateway": base.replace("https:", "wss:") + "/gateway_v2",
    }


def kbs(s, url):
    code = urllib.parse.parse_qs(url.query)["ch_code"][0]
    info = json.loads(get(f"https://cfpwwwapi.kbs.co.kr/api/v1/landing/live/channel_code/{code}"))
    if info.get("ret") != 0:
        raise ValueError(info.get("msg"))
    return {
        "stream": None, "source": "kbs", "kbs": code,
        "logo": info["channelMaster"].get("image_path_channel_logo"),
    }


KINDS = {"bigbradio.net": bigb, "listen.moe": listenmoe, "onair.kbs.co.kr": kbs}


def main():
    resolved = []
    for s in parse_md(SRC.read_text(encoding="utf-8")):
        url = urllib.parse.urlparse(s["page"])
        kind = KINDS.get(url.hostname.removeprefix("www."))
        try:
            if not kind:
                raise ValueError(f"don't know how to read {url.hostname}")
            r = {**s, **kind(s, url)}
            resolved.append(r)
            print(f"ok   {s['name']}: {r['source']} {r['stream'] or 'kbs ' + r['kbs']}")
        except Exception as e:  # keep going; one dead page shouldn't break the radio
            print(f"FAIL {s['name']}: {e}", file=sys.stderr)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by resolve_korea.py from stations-korea.md. Do not edit by hand.\n"
        "window.STATIONS = " + json.dumps(resolved, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(resolved)} stations to {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
