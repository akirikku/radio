#!/usr/bin/env python3
"""Resolve stations-istanbul.md into istanbul/stations.js for the İstanbul player.

stations-istanbul.md holds blocks of "Station name" followed by its İstanbul FM page URL.
The site's API (the same one istanbulfm.com.tr uses) lists every channel under /radyolar
with its HLS stream, channel ID and logo. We match each page URL to a channel there.
The player later polls that same /radyolar call for artist, title and artwork.

Run again whenever stations-istanbul.md changes:  python3 resolve_istanbul.py
"""
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from resolve_stations import parse_md

HERE = Path(__file__).resolve().parent
SRC = HERE / "stations-istanbul.md"
OUT = HERE / "istanbul" / "stations.js"

API = "https://api.istanbulfm.com.tr/v1/Route/get?url=/radyolar"
# The API rejects requests without the web client's identifying fields.
CLIENT = {"client": "web", "lang": "tr", "devicePlatform": "1", "deviceType": "0", "deviceID": "127.0.0.1"}


def fetch_channels():
    req = urllib.request.Request(
        API,
        data=urllib.parse.urlencode(CLIENT).encode(),
        headers={"Content-type": "application/x-www-form-urlencoded", "User-Agent": "Mozilla/5.0"},
    )
    data = json.load(urllib.request.urlopen(req, timeout=15))
    if data["meta"]["status"] != 200:
        raise RuntimeError(data["meta"].get("errorMessage"))

    channels = {}

    def walk(o):
        if isinstance(o, dict):
            if o.get("appClass") == "Channels" and o.get("media"):
                channels.setdefault(o["URL"], o)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(data)
    return channels


def main():
    stations = parse_md(SRC.read_text(encoding="utf-8"))
    channels = fetch_channels()
    resolved = []
    for s in stations:
        slug = urllib.parse.urlparse(s["page"]).path.strip("/").split("/")[-1]
        c = channels.get(slug)
        if not c:
            print(f"FAIL {s['name']}: no channel '{slug}' in /radyolar", file=sys.stderr)
            continue
        resolved.append({
            **s,
            "stream": c["media"][0],
            "channelId": c["ID"],
            "tagline": c.get("title"),
            "logo": c["image"]["prefix"] + "250x250" + c["image"]["suffix"],
        })
        print(f"ok   {s['name']}: {c['media'][0]}  (channel {c['ID']})")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by resolve_istanbul.py from stations-istanbul.md. Do not edit by hand.\n"
        "window.STATIONS = " + json.dumps(resolved, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(resolved)} stations to {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
